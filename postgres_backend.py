"""PostgreSQL adapter for the existing SQLite-style application queries."""
import re


class Row(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return tuple(self.values())[key]
        return super().__getitem__(key)


def row_factory(cursor):
    if cursor.description is None:
        return lambda values: values
    names = [column.name for column in cursor.description]
    return lambda values: Row(zip(names, values))


def translate(sql):
    sql = sql.replace('?', '%s').replace('char(12288)', 'chr(12288)')
    sql = re.sub(r'GROUP_CONCAT\((\w+\.\w+), "([^"]*)"\)',
                 lambda m: "STRING_AGG(" + m[1] + "::text, '" + m[2] + "')", sql)
    if 'INSERT OR IGNORE INTO' in sql:
        sql = sql.replace('INSERT OR IGNORE INTO', 'INSERT INTO')
        sql += ' ON CONFLICT DO NOTHING'
    return sql


class Result:
    def __init__(self, cursor, lastrowid=None):
        self.cursor = cursor
        self.lastrowid = lastrowid
        self.rowcount = cursor.rowcount

    def fetchone(self):
        return self.cursor.fetchone()

    def fetchall(self):
        return self.cursor.fetchall()

    def __iter__(self):
        return iter(self.cursor)


class Connection:
    def __init__(self, url):
        import psycopg
        self.raw = psycopg.connect(url, row_factory=row_factory,
                                   sslmode='require', connect_timeout=15,
                                   prepare_threshold=None)
        self.raw.execute('SET search_path TO course_app')
        self.raw.commit()

    def execute(self, sql, params=()):
        sql = translate(sql)
        match = re.match(r'INSERT INTO (\w+)', sql, re.I)
        returning = bool(match and match[1] in {
            'courses', 'classes', 'teachers', 'course_teachers', 'selections'
        })
        if returning:
            sql += ' RETURNING id'
        cursor = self.raw.execute(sql, params or None)
        inserted = cursor.fetchone() if returning else None
        return Result(cursor, inserted['id'] if inserted else None)

    def executescript(self, schema):
        schema = schema.replace('INTEGER PRIMARY KEY AUTOINCREMENT',
                                'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
        for statement in schema.split(';'):
            if statement.strip():
                self.raw.execute(statement)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()
